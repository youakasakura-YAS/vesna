inline void aesAddRoundKey(uint8_t st[16], const uint8_t* rk) {
    for (int i = 0; i < 16; ++i) st[i] ^= rk[i];
}
inline void aesSubBytes(uint8_t st[16]) {
    for (int i = 0; i < 16; ++i) st[i] = AES_SBOX[st[i]];
}
inline void aesInvSubBytes(uint8_t st[16]) {
    for (int i = 0; i < 16; ++i) st[i] = AES_RSBOX[st[i]];
}
inline void aesShiftRows(uint8_t st[16]) {
    uint8_t t[16];
    for (int r = 0; r < 4; ++r)
        for (int c = 0; c < 4; ++c) t[4*c+r] = st[4*((c+r)%4)+r];
    std::memcpy(st, t, 16);
}
inline void aesInvShiftRows(uint8_t st[16]) {
    uint8_t t[16];
    for (int r = 0; r < 4; ++r)
        for (int c = 0; c < 4; ++c) t[4*c+r] = st[4*((c-r+4)%4)+r];
    std::memcpy(st, t, 16);
}
inline uint8_t aesGmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; ++i) {
        if (b & 1) p ^= a;
        uint8_t hi = a & 0x80;
        a <<= 1;
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}
inline void aesMixColumns(uint8_t st[16]) {
    for (int c = 0; c < 4; ++c) {
        uint8_t* col = st + c*4;
        uint8_t a0=col[0], a1=col[1], a2=col[2], a3=col[3];
        col[0] = aesGmul(a0,2) ^ aesGmul(a1,3) ^ a2 ^ a3;
        col[1] = a0 ^ aesGmul(a1,2) ^ aesGmul(a2,3) ^ a3;
        col[2] = a0 ^ a1 ^ aesGmul(a2,2) ^ aesGmul(a3,3);
        col[3] = aesGmul(a0,3) ^ a1 ^ a2 ^ aesGmul(a3,2);
    }
}
inline void aesInvMixColumns(uint8_t st[16]) {
    for (int c = 0; c < 4; ++c) {
        uint8_t* col = st + c*4;
        uint8_t a0=col[0], a1=col[1], a2=col[2], a3=col[3];
        col[0] = aesGmul(a0,14) ^ aesGmul(a1,11) ^ aesGmul(a2,13) ^ aesGmul(a3,9);
        col[1] = aesGmul(a0,9) ^ aesGmul(a1,14) ^ aesGmul(a2,11) ^ aesGmul(a3,13);
        col[2] = aesGmul(a0,13) ^ aesGmul(a1,9) ^ aesGmul(a2,14) ^ aesGmul(a3,11);
        col[3] = aesGmul(a0,11) ^ aesGmul(a1,13) ^ aesGmul(a2,9) ^ aesGmul(a3,14);
    }
}
inline void aesExpandKey(const uint8_t key[32], uint8_t rk[240]) {
    for (int i = 0; i < 8; ++i) {
        rk[i*4] = key[i*4]; rk[i*4+1] = key[i*4+1]; rk[i*4+2] = key[i*4+2]; rk[i*4+3] = key[i*4+3];
    }
    for (int i = 8; i < 60; ++i) {
        uint8_t t[4];
        for (int j = 0; j < 4; ++j) t[j] = rk[(i-1)*4+j];
        if (i % 8 == 0) {
            uint8_t tmp = t[0]; t[0]=t[1]; t[1]=t[2]; t[2]=t[3]; t[3]=tmp;
            for (int j = 0; j < 4; ++j) t[j] = AES_SBOX[t[j]];
            static const uint8_t RCON[15] = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36,0x6c,0xd8,0xab,0x4d,0x9a};
            t[0] ^= RCON[i/8 - 1];
        } else if (i % 8 == 4) {
            for (int j = 0; j < 4; ++j) t[j] = AES_SBOX[t[j]];
        }
        for (int j = 0; j < 4; ++j) rk[i*4+j] = rk[(i-8)*4+j] ^ t[j];
    }
}
inline void aesEncryptBlock(const uint8_t in[16], uint8_t out[16], const uint8_t rk[240]) {
    uint8_t st[16];
    std::memcpy(st, in, 16);
    aesAddRoundKey(st, rk);
    for (int r = 1; r < 14; ++r) {
        aesSubBytes(st); aesShiftRows(st); aesMixColumns(st);
        aesAddRoundKey(st, rk + r*16);
    }
    aesSubBytes(st); aesShiftRows(st); aesAddRoundKey(st, rk + 14*16);
    std::memcpy(out, st, 16);
}
inline void aesDecryptBlock(const uint8_t in[16], uint8_t out[16], const uint8_t rk[240]) {
    uint8_t st[16];
    std::memcpy(st, in, 16);
    aesAddRoundKey(st, rk + 14*16);
    for (int r = 13; r >= 1; --r) {
        aesInvShiftRows(st); aesInvSubBytes(st);
        aesAddRoundKey(st, rk + r*16);
        aesInvMixColumns(st);
    }
    aesInvShiftRows(st); aesInvSubBytes(st); aesAddRoundKey(st, rk);
    std::memcpy(out, st, 16);
}

// ---- AES-256-CBC + PKCS7（密钥字符串经 SHA-256 派生 32 字节，IV 固定全零） ----
inline void aesKeyFromStr(const std::string& keyStr, uint8_t kb[32]) {
    std::string h = sha256Hex(keyStr);
    for (int i = 0; i < 32; ++i) {
        auto hv = [](char c) -> int {
            if (c >= '0' && c <= '9') return c - '0';
            if (c >= 'a' && c <= 'f') return c - 'a' + 10;
            if (c >= 'A' && c <= 'F') return c - 'A' + 10;
            return 0;
        };
        kb[i] = (uint8_t)(hv(h[i*2]) * 16 + hv(h[i*2+1]));
    }
}

inline std::string aesEncryptCbc(const std::string& data, const std::string& keyStr) {
    uint8_t kb[32];
    aesKeyFromStr(keyStr, kb);
    uint8_t rk[240];
    aesExpandKey(kb, rk);
    uint8_t prev[16] = {0};
    std::string out;
    out.reserve(data.size() + 16);
    size_t rem = data.size() % 16;
    size_t pad = 16 - rem;
    if (pad == 0) pad = 16;
    size_t blocks = data.size() / 16 + 1;
    for (size_t b = 0; b < blocks; ++b) {
        uint8_t buf[16];
        for (int j = 0; j < 16; ++j) {
            size_t idx = b*16 + j;
            uint8_t plain = (idx < data.size()) ? (uint8_t)data[idx] : (uint8_t)pad;
            buf[j] = plain ^ prev[j];
        }
        aesEncryptBlock(buf, buf, rk);
        std::memcpy(prev, buf, 16);
        out.append((const char*)buf, 16);
    }
    return out;
}

inline std::string aesDecryptCbc(const std::string& data, const std::string& keyStr) {
    uint8_t kb[32];
    aesKeyFromStr(keyStr, kb);
    uint8_t rk[240];
    aesExpandKey(kb, rk);
    uint8_t prev[16] = {0};
    std::string out;
    out.reserve(data.size());
    for (size_t i = 0; i + 16 <= data.size(); i += 16) {
        uint8_t ct[16], buf[16];
        std::memcpy(ct, data.data() + i, 16);
        aesDecryptBlock(ct, buf, rk);
        for (int j = 0; j < 16; ++j) buf[j] ^= prev[j];
        std::memcpy(prev, ct, 16);
        out.append((const char*)buf, 16);
    }
    if (!out.empty()) {
        uint8_t pad = (uint8_t)out.back();
        if (pad >= 1 && pad <= 16) {
            bool ok = true;
            for (int j = 0; j < pad; ++j)
                if ((uint8_t)out[out.size() - 1 - j] != pad) { ok = false; break; }
            if (ok) out.resize(out.size() - pad);
        }
    }
    return out;
}

